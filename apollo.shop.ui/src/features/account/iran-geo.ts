export function citiesForProvince(province: string): string[] {
  if (!province) return [];
  const cities = IRAN_CITIES_BY_PROVINCE[province as IranProvince];
  if (!cities) return [];
  return [...new Set(cities.map((c) => c.trim()).filter(Boolean))];
}

